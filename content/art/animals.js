const hexToRgb = (h) => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)];

// 점 그림 → RGBA (16×16), 어두운 외곽선
export function animalPixels(species, frame) {
  const { pal, frames } = ART[species];
  const rows = frames[frame];
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error(`동물 그림 ${species}.${frame}: 16×16이 아님`);
  const d = new Uint8ClampedArray(16 * 16 * 4);
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === '.' || !pal[ch]) return;
    const [r, g, b] = hexToRgb(pal[ch]);
    const i = (y * 16 + x) * 4;
    d[i] = r; d[i + 1] = g; d[i + 2] = b; d[i + 3] = 255;
  }));
  const out = new Uint8ClampedArray(d);
  const a = (x, y) => (x < 0 || y < 0 || x >= 16 || y >= 16 ? 0 : d[(y * 16 + x) * 4 + 3]);
  for (let y = 0; y < 16; y += 1) for (let x = 0; x < 16; x += 1) {
    if (a(x, y) || !(a(x - 1, y) || a(x + 1, y) || a(x, y - 1) || a(x, y + 1))) continue;
    const i = (y * 16 + x) * 4;
    out[i] = 20; out[i + 1] = 27; out[i + 2] = 27; out[i + 3] = 255;
  }
  return out;
}

